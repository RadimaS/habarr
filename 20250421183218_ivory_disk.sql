/*
  # Create Culture Tables

  1. New Tables
    - `culture_cards`
      - `id` (uuid, primary key)
      - `title` (text, not null)
      - `description` (text, not null)
      - `icon` (text, not null)
      - `color` (text, not null)
      - `created_at` (timestamp with timezone)
    
    - `culture_content`
      - `id` (uuid, primary key)
      - `card_id` (uuid, foreign key to culture_cards)
      - `title` (text, not null)
      - `text` (text, not null)
      - `created_at` (timestamp with timezone)

  2. Security
    - Enable RLS on both tables
    - Add policies for public read access
*/

-- Drop existing tables if they exist
DROP TABLE IF EXISTS public.culture_content;
DROP TABLE IF EXISTS public.culture_cards;

-- Create culture_cards table
CREATE TABLE public.culture_cards (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  description text NOT NULL,
  icon text NOT NULL,
  color text NOT NULL,
  created_at timestamptz DEFAULT now()
);

-- Create culture_content table
CREATE TABLE public.culture_content (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  card_id uuid NOT NULL REFERENCES public.culture_cards(id) ON DELETE CASCADE,
  title text NOT NULL,
  text text NOT NULL,
  created_at timestamptz DEFAULT now()
);

-- Enable RLS
ALTER TABLE public.culture_cards ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.culture_content ENABLE ROW LEVEL SECURITY;

-- Add RLS policies
CREATE POLICY "Enable read access for all users" ON public.culture_cards
  FOR SELECT TO public USING (true);

CREATE POLICY "Enable read access for all users" ON public.culture_content
  FOR SELECT TO public USING (true);

